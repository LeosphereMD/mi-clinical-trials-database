"""Registry analyses (SPEC "Analyses" 1-4) from the database only.

Usage:  .venv\\Scripts\\python scripts\\registry_analyses.py

Reads data/ami_trials.db (never writes it). Writes review/registry_analyses.md
(numbers only, no paper quotes). Every table is shown for all trials and for
acute-only trials (timing_after_mi = acute, decision 16). Trials with an empty
value are counted, never dropped silently. Withdrawn trials are left out of the
main analyses and listed separately; terminated trials stay in and are also
listed separately (owner, 2026-11-17).
"""
import re
import sqlite3
import sys
from collections import Counter, defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from load_drug_classes import NON_DRUG_BIOLOGICALS  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
DB = ROOT / "data" / "ami_trials.db"
OUT = ROOT / "review" / "registry_analyses.md"
TYPES = ["clinical only", "surrogate only", "patient-reported only", "mixed", "other"]
# Analyses 2: composite wording (SPEC "Analyses", 2). Words match whole words only.
COMPOSITE_WORDS = ["composite", "mace", "macce", "combined", "hierarchical", "win ratio",
                   "net clinical", "any of", "or", "and", "endpoint"]
COMPOSITE_CHARS = [",", ";", "/", "+"]


def pct(n, d):
    return f"{n} ({100 * n / d:.0f}%)" if d else f"{n} (-)"


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "|" + "---|" * len(header)]
    out += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(out)


def is_single_event(row):
    category, cws, measure = row
    if category != "clinical event" or cws != "no":
        return False
    text = (measure or "").lower()
    if any(c in text for c in COMPOSITE_CHARS):
        return False
    return not any(re.search(rf"\b{re.escape(w)}\b", text) for w in COMPOSITE_WORDS)


def main():
    con = sqlite3.connect(DB)
    trials = con.execute(
        "select nct_id, title, phase_label, overall_status, why_stopped_category, enrollment, "
        "primary_outcome_type, timing_after_mi from trials").fetchall()
    cols = ["nct", "title", "phase", "status", "why_cat", "enrollment", "pot", "timing"]
    trials = [dict(zip(cols, t)) for t in trials]
    prim = {}
    for nct, cat, cws, measure in con.execute(
            "select nct_id, outcome_category, composite_with_surrogate, measure "
            "from registered_outcomes where outcome_type = 'primary'"):
        prim.setdefault(nct, []).append((cat, cws, measure))
    run = con.execute("select run_date from fetch_runs order by run_id desc limit 1").fetchone()
    # Analyses 4: DRUG/BIOLOGICAL interventions with role and class (decisions 21, 36).
    drugs = defaultdict(list)
    for nct, role, gname, parent, cls in con.execute(
            "select i.nct_id, i.intervention_role, i.generic_name, c.class_parent, c.drug_class "
            "from interventions i left join drug_classes c on c.drug = i.generic_name "
            "where i.intervention_type in ('DRUG', 'BIOLOGICAL')"):
        drugs[nct].append((role, gname, parent, cls))

    # Withdrawn trials (no patients enrolled) are left out of the main analyses and listed
    # separately; terminated trials stay in and are also listed (SPEC "Analyses", 2026-11-17).
    main_trials = [t for t in trials if t["status"] != "WITHDRAWN"]
    groups = {"All trials": main_trials,
              "Acute-only trials": [t for t in main_trials if t["timing"] == "acute"]}
    lines = ["# Registry analyses", "",
             f"Source: `data/ami_trials.db`, registry snapshot downloaded {run[0] if run else '(unknown)'}. "
             "Numbers only; generated by `scripts/registry_analyses.py`. Every analysis is shown for all "
             "trials and for acute-only trials (decision 16). Withdrawn trials (no patients enrolled) are "
             "left out of the main analyses and listed separately; terminated trials are included and also "
             "listed separately.", ""]
    timing = Counter(t["timing"] for t in main_trials)
    withdrawn = len(trials) - len(main_trials)
    lines += ["## Dataset", "",
              table(["", "Trials"], [["In the database", len(trials)],
                                     ["Withdrawn (left out of the main analyses)", withdrawn],
                                     ["In the main analyses", len(main_trials)],
                                     ["Phase 3", sum(t["phase"] == "PHASE3" for t in main_trials)],
                                     ["Phase 2/3", sum(t["phase"] == "PHASE2/PHASE3" for t in main_trials)],
                                     ["Timing: acute", timing.get("acute", 0)],
                                     ["Timing: recent", timing.get("recent", 0)],
                                     ["Timing: prior", timing.get("prior", 0)],
                                     ["Timing: empty (counted, not dropped)", timing.get(None, 0)]]), ""]
    status = Counter(t["status"] for t in trials)
    lines += ["Recruitment status (all trials):", "",
              table(["Status", "Trials"], [[s, n] for s, n in status.most_common()]), ""]

    for gname, g in groups.items():
        n = len(g)
        lines += [f"## {gname} (n = {n})", ""]
        # 1. primary outcome type
        lines += ["### 1. Share of trials by primary outcome type", ""]
        rows = []
        for ty in TYPES + [None]:
            label = ty if ty else "empty (counted, not dropped)"
            all_ = sum(t["pot"] == ty for t in g)
            p3 = [t for t in g if t["phase"] == "PHASE3"]
            p23 = [t for t in g if t["phase"] == "PHASE2/PHASE3"]
            rows.append([label, pct(all_, n), pct(sum(t["pot"] == ty for t in p3), len(p3)),
                         pct(sum(t["pot"] == ty for t in p23), len(p23))])
        lines += [table(["Primary outcome type", f"All (n={n})",
                         f"Phase 3 (n={sum(t['phase'] == 'PHASE3' for t in g)})",
                         f"Phase 2/3 (n={sum(t['phase'] == 'PHASE2/PHASE3' for t in g)})"], rows), ""]
        cws = sum(any(r[1] == "yes" for r in prim.get(t["nct"], [])) for t in g)
        lines += [f"Trials with at least one primary outcome flagged composite_with_surrogate: {pct(cws, n)}.", ""]
        # 2. split composites
        split = []
        for t in g:
            rows_ = prim.get(t["nct"], [])
            singles = sum(is_single_event(r) for r in rows_)
            if singles >= 2:
                has_surr = any(r[0] == "surrogate or lab measure" for r in rows_)
                split.append((t["nct"], singles, len(rows_), "yes" if has_surr else "no"))
        lines += ["### 2. Split composites (decision 18)", "",
                  f"Trials with 2 or more single-event primary rows: {len(split)}"
                  f"; of these with a surrogate primary row as well: {sum(s[3] == 'yes' for s in split)}.", ""]
        if split:
            lines += [table(["Trial", "Single-event rows", "Primary rows", "Also a surrogate row"],
                            [list(s) for s in split]), ""]
        # 3. small surrogate-only
        surr = [t for t in g if t["pot"] == "surrogate only"]
        small = [t for t in surr if t["enrollment"] is not None and t["enrollment"] < 500]
        no_enr = sum(t["enrollment"] is None for t in surr)
        lines += ["### 3. Small surrogate-only trials (<500 patients) (decision 19)", "",
                  table(["", "Trials"], [["Small surrogate-only trials", len(small)],
                                         ["Share of all trials in this group", pct(len(small), n)],
                                         ["Share of surrogate-only trials", pct(len(small), len(surr))],
                                         ["Surrogate-only trials with no enrollment figure", no_enr]]), ""]
        # 4. drug classes, study drugs only (decisions 21 and 36)
        ivs = [(t["nct"], *d) for t in g for d in drugs.get(t["nct"], [])]
        study = [x for x in ivs if x[1] == "study drug"]
        non_drug = [x for x in study if x[2] in NON_DRUG_BIOLOGICALS]
        classed = [x for x in study if x[4] is not None]
        unclassed = [x for x in study if x[4] is None and x[2] not in NON_DRUG_BIOLOGICALS]
        no_role = [x for x in ivs if x[1] is None]
        by_parent, by_class = defaultdict(set), defaultdict(set)
        iv_parent, iv_class = Counter(), Counter()
        for nct, _, _, parent, cls in classed:
            by_parent[parent].add(nct); by_class[cls].add(nct)
            iv_parent[parent] += 1; iv_class[cls] += 1
        with_class = len({x[0] for x in classed})
        lines += ["### 4. Drug classes (study drugs only; decisions 21 and 36)", "",
                  table(["", "Count"], [
                      ["DRUG/BIOLOGICAL interventions", len(ivs)],
                      ["  study drug", len(study)],
                      ["    with a class", len(classed)],
                      ["    non-drug biologicals (cell therapy, blood; left out)", len(non_drug)],
                      ["    no class (counted, not dropped)", len(unclassed)],
                      ["  comparator or background (left out)", len(ivs) - len(study) - len(no_role)],
                      ["  no role yet (counted, not dropped)", len(no_role)],
                      ["Trials with at least one classed study drug", pct(with_class, n)]]), "",
                  "A trial can test drugs from more than one class, so trial shares do not add up "
                  "to 100%. Share = share of trials in this group.", "",
                  "By parent class:", "",
                  table(["Parent class", "Trials", "Study-drug interventions"],
                        [[k, pct(len(v), n), iv_parent[k]] for k, v in
                         sorted(by_parent.items(), key=lambda kv: (-len(kv[1]), kv[0]))]), "",
                  "By parent: subclass:", "",
                  table(["Class", "Trials", "Study-drug interventions"],
                        [[k, len(v), iv_class[k]] for k, v in
                         sorted(by_class.items(), key=lambda kv: (-len(kv[1]), kv[0]))]), ""]

    # terminated and withdrawn, separately
    lines += ["## Terminated and withdrawn trials (reported separately)", ""]
    for st in ("TERMINATED", "WITHDRAWN"):
        g = [t for t in trials if t["status"] == st]
        lines += [f"### {st.title()} (n = {len(g)}; acute-only {sum(t['timing'] == 'acute' for t in g)})", "",
                  table(["Trial", "Phase", "Timing", "Enrollment", "Primary outcome type", "why_stopped category"],
                        [[t["nct"], t["phase"], t["timing"] or "empty", t["enrollment"],
                          t["pot"] or "empty", t["why_cat"] or "empty"] for t in sorted(g, key=lambda x: x["nct"])]), ""]
        cats = Counter(t["why_cat"] for t in g)
        lines += ["why_stopped categories: " + ", ".join(f"{k or 'empty'} {v}" for k, v in cats.most_common()) + ".", ""]

    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT.relative_to(ROOT)}")
    print("=== Summary ===")
    print(f"Trials in: {len(trials)}")
    print(f"Primary outcome rows in: {sum(len(v) for v in prim.values())}")
    print(f"DRUG/BIOLOGICAL interventions in: {sum(len(v) for v in drugs.values())}")
    print(f"Trials out (main analyses): {len(main_trials)}  (acute-only {len(groups['Acute-only trials'])});"
          " empty values are counted in their own row")
    print(f"Skipped from the main analyses: {withdrawn} (withdrawn, listed separately)")


if __name__ == "__main__":
    main()
